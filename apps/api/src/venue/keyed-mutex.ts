/**
 * In-process mutex per key (FIFO). Used for per-account reservation sections.
 * Lock order rule (ADR-0019): an account lock is only ever taken while already
 * inside an instrument's serialized section, and no instrument section is ever
 * entered while holding an account lock, so the wait-for graph cannot cycle.
 */
export class KeyedMutex {
  private readonly tails = new Map<string, Promise<void>>();

  async run<T>(key: string, fn: () => Promise<T>): Promise<T> {
    const previous = this.tails.get(key) ?? Promise.resolve();
    let release!: () => void;
    const current = new Promise<void>((resolve) => {
      release = resolve;
    });
    const tail = previous.then(() => current);
    this.tails.set(key, tail);
    await previous;
    try {
      return await fn();
    } finally {
      release();
      if (this.tails.get(key) === tail) this.tails.delete(key);
    }
  }
}
